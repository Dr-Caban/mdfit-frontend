// Writes the one shared site header into every public page, so it is identical everywhere.
// Edit the header HERE (markup) or in /site-header.css (look) and /site-header.js (menu), then run:
//   node scripts/site-header.js && node scripts/version-assets.js
// The header sits between <!-- site-header --> and <!-- /site-header --> in each page; re-running replaces it.
// The first run also swaps out the older per-section headers (home .nav, .gd-nav, .legal-top, .in-top).
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
// The member app, the admin portal and the workspace demo have their own chrome, so they keep it.
const SKIP = new Set(["account.html", "admin.html", "workspace-preview.html"]);

const LINKS = [
  { href: "/conditions/", text: "Conditions", section: "conditions" },
  { href: "/treatments/", text: "Treatments", section: "treatments" },
  { href: "/areas/", text: "Areas", section: "areas" },
  { href: "/blog/", text: "Blog", section: "blog" },
  { href: "/#dr", text: "Dr. Jared" },
  { href: "/#reviews", text: "Reviews" },
  { href: "/events", text: "Events", section: "events" }
];

function header(rel) {
  const section = rel.split("/")[0].replace(/\.html$/, "");
  const home = rel === "index.html";
  const links = LINKS.map((l) => `        <a href="${home && l.href.startsWith("/#") ? l.href.slice(1) : l.href}"${l.section === section ? ' aria-current="page"' : ""}>${l.text}</a>`).join("\n");
  return `<!-- site-header: generated by scripts/site-header.js, edit it there -->
  <header class="sh" id="top">
    <div class="sh-inner">
      <a href="/" class="sh-brand" aria-label="MD Fit home"><img src="/assets/logo.webp" alt="MD Fit" width="160" height="160"><span class="sh-sub">Physical Rehab &amp; Fitness</span></a>
      <button class="sh-menu-btn" type="button" aria-label="Menu" aria-expanded="false" aria-controls="sh-menu"><span></span><span></span><span></span></button>
      <nav class="sh-menu" id="sh-menu" aria-label="Main">
${links}
        <a href="tel:+19413130562" class="sh-phone" data-phone-link>941-313-0562</a>
        <a href="/login" class="sh-app" data-account-link>Open the app</a>
        <a href="${home ? "#book" : "/book"}" class="sh-book">Book evaluation</a>
      </nav>
    </div>
  </header>
  <!-- /site-header -->`;
}

const OLD = [
  /<!-- site-header[\s\S]*?<!-- \/site-header -->/,
  /<header class="nav"[^>]*>[\s\S]*?<\/header>/,
  /<nav class="gd-nav">[\s\S]*?<\/nav>/,
  /<header class="legal-top"[^>]*>[\s\S]*?<\/header>/,
  /<header class="in-top"[^>]*>[\s\S]*?<\/header>/
];

const pages = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) { if (!/^[._]|^(node_modules|scripts)$/.test(e.name)) walk(p); } else if (e.name.endsWith(".html")) pages.push(p);
  }
})(root);

let changed = 0;
for (const file of pages.sort()) {
  const rel = path.relative(root, file).replace(/\\/g, "/");
  if (SKIP.has(rel)) continue;
  let s = fs.readFileSync(file, "utf8");
  const before = s, h = header(rel);
  const old = OLD.find((re) => re.test(s));
  if (old) s = s.replace(old, h);
  else s = s.replace(/(<body[^>]*>\s*(?:<a class="skip"[^>]*>[^<]*<\/a>\s*)?)/, `$1${h}\n  `);
  if (!s.includes("<!-- /site-header -->")) { console.error("could not place the header in", rel); process.exitCode = 1; continue; }
  if (!/href="\/site-header\.css/.test(s)) s = s.replace("</head>", `  <link rel="stylesheet" href="/site-header.css">\n</head>`);
  if (!/src="\/site-header\.js/.test(s)) s = s.replace("</head>", `  <script src="/site-header.js" defer></script>\n</head>`);
  if (s !== before) { fs.writeFileSync(file, s); changed++; }
}
console.log(`site header: ${changed} page(s) updated`);
